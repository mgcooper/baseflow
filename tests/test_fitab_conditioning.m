   % Public NLS fitting must not depend on discharge units or roundoff.
   % The saved vectors derive from the public Kuparuk fixture. Events 77,
   % 62 and 38 are checksum-bound in the October 28 repair evidence.

   properties (TestParameter)
      Event = {77, 62, 38}
   end

   properties (Constant, Access=private)
      % Roundoff must remain much smaller than the scientific btol=5e-4.
      exponentTolerance = 1e-6
      intervalTolerance = 2e-5
      coefficientTolerance = 1e-4
   end

   methods (Test)
      function savedInputPerturbations(testCase,Event)
         [q1,d1,q2,d2] = testCase.vectors(Event);
         [expected,ok1] = baseflow.fitab(q1,d1,'nls');
         [returned,ok2] = baseflow.fitab(q2,d2,'nls');
         testCase.verifyTrue(ok1 && ok2);
         testCase.verifyEqual(returned.b,expected.b, ...
            'AbsTol',testCase.exponentTolerance);
         testCase.verifyEqual([returned.bL returned.bH], ...
            [expected.bL expected.bH],'AbsTol',testCase.intervalTolerance);
      end

      function physicalUnitInvariance(testCase,Event)
         [q,dqdt] = testCase.vectors(Event);
         unitScale = 1e6;
         expected = baseflow.fitab(q,dqdt,'nls');
         returned = baseflow.fitab(q/unitScale,dqdt/unitScale,'nls');
         testCase.verifyEqual(returned.b,expected.b, ...
            'AbsTol',testCase.exponentTolerance);
         testCase.verifyEqual([returned.bL returned.bH], ...
            [expected.bL expected.bH],'AbsTol',testCase.intervalTolerance);
         a_returned = returned.a*unitScale/unitScale^returned.b;
         testCase.verifyEqual(a_returned,expected.a, ...
            'RelTol',testCase.coefficientTolerance);
      end

      function responseUnitsPreserveIntervals(testCase,Event)
         [q,dqdt] = testCase.vectors(Event);
         responseScale = 1e3;
         expected = baseflow.fitab(q,dqdt,'nls');
         returned = baseflow.fitab(q,responseScale*dqdt,'nls');
         testCase.verifyEqual(returned.b,expected.b, ...
            'AbsTol',testCase.exponentTolerance);
         testCase.verifyEqual([returned.a returned.aL returned.aH] ...
            /responseScale,[expected.a expected.aL expected.aH], ...
            'RelTol',testCase.coefficientTolerance);
         testCase.verifyEqual([returned.bL returned.bH], ...
            [expected.bL expected.bH],'AbsTol',testCase.intervalTolerance);
      end

      function knownPowerLaw(testCase)
         q = logspace(0,2,40)';
         a_expected = 0.02;
         b_expected = 1.5;
         dqdt = -a_expected*q.^b_expected;
         returned = baseflow.fitab(q,dqdt,'nls');
         testCase.verifyEqual(returned.a,a_expected, ...
            'RelTol',testCase.exponentTolerance);
         testCase.verifyEqual(returned.b,b_expected, ...
            'AbsTol',testCase.exponentTolerance);
      end
   end

