function requireflat(isflat,soln1,soln2)
   %REQUIREFLAT Reject unsupported sloped porosity requests before fitting.
   % Raw sloped formulas remain in fitphi for research, not callable results.
   sloped = {'BR94','RS06','RS06b1','Brutsaert, 1994', ...
      'Rupp and Selker, 2006 b=1','Rupp and Selker, 2006 b=f(n)','all'};
   % Empty logical inputs must not pass through an unsupported geometry path.
   if ~isscalar(isflat) || ~isflat || any(strcmpi(soln1,sloped)) || ...
         any(strcmpi(soln2,sloped))
      error('baseflow:unsupportedSlopedAquifer', ...
         ['Sloped porosity workflows and all-pair requests ' ...
         'are unsupported. ' ...
         'Use isflat=true and a supported flat solution pair.']);
   end
end
